#!/bin/bash
# Refuse to start the server if any jar it can load is missing from, differs
# from, or is not listed in scripts/server.lock.
# Usage: ./scripts/verify-server-jars.sh [SERVER_DIR]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SERVER="${1:-$ROOT/server-cardboard}"
LOCK="$ROOT/scripts/server.lock"
# Rebuilt locally, so it is compared with the build output instead of the lock.
MOD_JAR=mods/higgs-villagers-0.1.0.jar
MOD_BUILD="$ROOT/mod/build/libs/higgs-villagers-0.1.0.jar"
# Built by setup-linux.sh; it may only hold the files in scripts/fabric-launch/.
LOADER_JAR=.fabric/server/fabric-loader-server-0.20.1-minecraft-26.1.2.jar
LAUNCH_SRC="$ROOT/scripts/fabric-launch"

die() { echo "Refusing to start: $*" >&2; exit 1; }
if command -v sha512sum >/dev/null; then sha512() { sha512sum "$@"; }; else sha512() { shasum -a 512 "$@"; }; fi

cd "$SERVER"
entries="$(grep -v '^#' "$LOCK" | cut -f1,2)"
listed="$(cut -f1 <<<"$entries" | LC_ALL=C sort)"
# .fabric/processedMods is regenerated by Fabric Loader from the locked Fabric API.
present="$({ find fabric-server-launch.jar .fabric/server versions libraries lib mods plugins \
  -type f -name '*.jar' 2>/dev/null || true; } | LC_ALL=C sort)"

missing="$({ LC_ALL=C comm -23 <(echo "$listed") <(echo "$present"); echo "$LOADER_JAR"; } \
  | while read -r path; do if [[ -n "$path" && ! -f "$path" ]]; then echo "$path"; fi; done)"
[[ -z "$missing" ]] || die "$(grep -c . <<<"$missing") jars from scripts/server.lock are missing, so the
launcher would download them unchecked. On Linux run ./scripts/setup-linux.sh; elsewhere download
each source in scripts/server.lock into server-cardboard/. First missing: $(head -1 <<<"$missing")"

unlisted="$(LC_ALL=C comm -13 <(echo "$listed") <(echo "$present") | grep -vx -e "$MOD_JAR" -e "$LOADER_JAR" || true)"
[[ -z "$unlisted" ]] || die "these jars are not in scripts/server.lock:
$unlisted
Verify them upstream and add them to the lock, or remove them."

bad="$(awk -F'\t' '{print $2 "  " $1}' <<<"$entries" | sha512 -c --quiet 2>&1)" \
  || die "these jars differ from scripts/server.lock:
$bad"

if [[ -f "$MOD_JAR" ]]; then
  [[ -f "$MOD_BUILD" ]] || die "no build to compare $MOD_JAR with; run ./scripts/build-mod.sh."
  cmp -s "$MOD_JAR" "$MOD_BUILD" || die "$MOD_JAR differs from $MOD_BUILD; copy the current build in."
fi
[[ "$(unzip -Z1 "$LOADER_JAR" | grep -v '/$' | LC_ALL=C sort | tr '\n' ' ')" \
    == 'META-INF/MANIFEST.MF fabric-server-launch.properties ' ]] \
  && unzip -p "$LOADER_JAR" META-INF/MANIFEST.MF | tr -d '\r' | cmp -s - "$LAUNCH_SRC/META-INF/MANIFEST.MF" \
  && unzip -p "$LOADER_JAR" fabric-server-launch.properties | cmp -s - "$LAUNCH_SRC/fabric-server-launch.properties" \
  || die "$LOADER_JAR differs from scripts/fabric-launch/; run ./scripts/setup-linux.sh to rebuild it."

echo "Verified $(grep -c . <<<"$present") server jars against scripts/server.lock."
